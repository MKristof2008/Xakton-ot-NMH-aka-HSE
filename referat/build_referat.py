def load_facts():
    """Фактические числа: тесты, метрики, база, автопилот."""
    facts = {}

    # Тесты: полный прогон без сети.
    try:
        out = subprocess.run(
            [sys.executable, "-m", "pytest", "-q"],
            cwd=PROJECT, capture_output=True, text=True, timeout=900,
            encoding="utf-8", errors="replace",
        )
        tail = (out.stdout or "").strip().splitlines()[-1]
        facts["tests_line"] = tail
        parts = tail.split(",")
        for part in parts:
            part = part.strip()
            if part.endswith("passed"):
                facts["tests_passed"] = part.split()[0]
            elif part.endswith("skipped"):
                facts["tests_skipped"] = part.split()[0]
    except Exception as exc:  # прогон недоступен — берём последнюю известную цифру
        facts["tests_line"] = f"не удалось прогнать тесты: {exc}"

    report = json.loads((PROJECT / "ml" / "data" / "eval_report.json").read_text(encoding="utf-8"))
    facts["eval"] = report["summary"]

    kb = json.loads((PROJECT / "ml" / "lakmus" / "data" / "kb_facts.json").read_text(encoding="utf-8"))
    facts["kb_topics"] = len(kb["topics"])
    facts["kb_facts"] = sum(len(t["facts"]) for t in kb["topics"])

    model_path = PROJECT / "autopilot" / "data" / "models"
    pointer = model_path / "active.json"
    if pointer.exists():
        active = json.loads(pointer.read_text(encoding="utf-8"))
        meta_path = model_path / f"fake_model_{active['version']}.json"
        if meta_path.exists():
            facts["model"] = json.loads(meta_path.read_text(encoding="utf-8"))
    return facts


