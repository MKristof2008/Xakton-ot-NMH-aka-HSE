def update_fields(path: Path):
    """Обновить оглавление и сохранить PDF через Word, если он установлен."""
    try:
        import win32com.client  # noqa: F401
    except ImportError:
        print("pywin32 не установлен — оглавление обновите в Word вручную (F9)")
        return
    import win32com.client as win32

    word = win32.gencache.EnsureDispatch("Word.Application")
    word.Visible = False
    try:
        doc = word.Documents.Open(str(path))
        doc.Fields.Update()
        for toc in doc.TablesOfContents:
            toc.Update()
        doc.Save()
        pdf = path.with_suffix(".pdf")
        doc.SaveAs2(str(pdf), FileFormat=17)
        doc.Close(False)
        print("saved", pdf)
    finally:
        word.Quit()


